-- C3B3D candidate ONLY. Execute exclusively in disposable PostgreSQL.
-- Does not alter archivito_inc, live RPCs, Storage, or the hard-closed gate.
create schema archivito_inc_cert_candidate;
revoke all on schema archivito_inc_cert_candidate from public;

create table archivito_inc_cert_candidate.windows (
  id uuid primary key,
  archive_id uuid not null,
  owner_id uuid not null,
  editor_id uuid not null check (editor_id <> owner_id),
  key_id text not null check (key_id ~ '^[0-9a-f]{64}$'),
  opened_at timestamptz not null,
  expires_at timestamptz not null,
  enabled boolean not null default false,
  quota_bytes bigint not null check (quota_bytes between 1 and 67108864),
  max_operations integer not null check (max_operations between 1 and 24),
  check (expires_at > opened_at and expires_at <= opened_at + interval '15 minutes')
);
create table archivito_inc_cert_candidate.fences (
  window_id uuid not null references archivito_inc_cert_candidate.windows(id),
  operation_id uuid not null,
  actor uuid not null,
  memory_id uuid not null,
  revision integer not null check (revision between 1 and 24),
  wire_digest text not null check (wire_digest ~ '^[0-9a-f]{64}$'),
  reserved_bytes bigint not null check (reserved_bytes between 1 and 67108864),
  generation bigint not null check (generation >= 1),
  token uuid not null,
  lease_until timestamptz not null,
  primary key(window_id,operation_id)
);
alter table archivito_inc_cert_candidate.windows enable row level security;
alter table archivito_inc_cert_candidate.fences enable row level security;
revoke all on all tables in schema archivito_inc_cert_candidate from public;

-- The trusted future wrapper must verify fresh membership/key/session independently.
-- Lock the window BEFORE inspecting/locking a fence; all wrappers use this order.
create function archivito_inc_cert_candidate.guard_window(
  p_window uuid,p_archive uuid,p_actor uuid,p_key text,p_memory uuid
) returns archivito_inc_cert_candidate.windows
language plpgsql security invoker set search_path='' as $$
declare w archivito_inc_cert_candidate.windows%rowtype; t timestamptz;
begin
  select * into w from archivito_inc_cert_candidate.windows where id=p_window for update;
  t:=clock_timestamp();
  if not found or w.enabled is distinct from true or t < w.opened_at or t >= w.expires_at
     or p_archive is distinct from w.archive_id or p_key is distinct from w.key_id
     or p_actor is null or p_actor not in (w.owner_id,w.editor_id)
     or p_memory is null or p_memory not in (
       '73ac551b-2df8-4da7-91b8-4adf18d83901'::uuid,
       '73ac551b-2df8-4da7-91b8-4adf18d83902'::uuid,
       '73ac551b-2df8-4da7-91b8-4adf18d83903'::uuid)
  then raise exception using errcode='42501',message='certification denied'; end if;
  return w;
end $$;

-- Claim only after expiry, same actor/scope/digest, no new reservation on takeover.
-- The token is generated by PostgreSQL, not the browser. No automatic reclamation.
create function archivito_inc_cert_candidate.claim(
  p_window uuid,p_archive uuid,p_actor uuid,p_key text,p_memory uuid,
  p_operation uuid,p_revision integer,p_digest text,p_bytes bigint
) returns archivito_inc_cert_candidate.fences
language plpgsql security invoker set search_path='' as $$
declare w archivito_inc_cert_candidate.windows%rowtype; f archivito_inc_cert_candidate.fences%rowtype;
        t timestamptz; used bigint; n bigint;
begin
  w:=archivito_inc_cert_candidate.guard_window(p_window,p_archive,p_actor,p_key,p_memory);
  if p_operation is null or p_revision is null or p_revision not between 1 and 24
     or (p_revision=1 and p_actor is distinct from w.owner_id)
     or p_digest is null or p_digest !~ '^[0-9a-f]{64}$'
     or p_bytes is null or p_bytes not between 1 and w.quota_bytes
  then raise exception using errcode='42501',message='certification denied'; end if;
  select * into f from archivito_inc_cert_candidate.fences
    where window_id=p_window and operation_id=p_operation for update;
  t:=clock_timestamp();
  if t>=w.expires_at then raise exception using errcode='42501',message='certification expired';end if;
  if found then
    if f.actor is distinct from p_actor or f.memory_id is distinct from p_memory
       or f.revision is distinct from p_revision or f.wire_digest is distinct from p_digest
       or f.reserved_bytes is distinct from p_bytes or f.lease_until>t
    then raise exception using errcode='42501',message='certification lease denied';end if;
    update archivito_inc_cert_candidate.fences
       set generation=generation+1,token=gen_random_uuid(),lease_until=least(t+interval '30 seconds',w.expires_at)
       where window_id=p_window and operation_id=p_operation returning * into f;
  else
    select coalesce(sum(reserved_bytes),0),count(*) into used,n from archivito_inc_cert_candidate.fences where window_id=p_window;
    if used+p_bytes>w.quota_bytes or n>=w.max_operations
    then raise exception using errcode='42501',message='certification quota';end if;
    insert into archivito_inc_cert_candidate.fences values(
      p_window,p_operation,p_actor,p_memory,p_revision,p_digest,p_bytes,1,
      gen_random_uuid(),least(t+interval '30 seconds',w.expires_at)) returning * into f;
  end if;
  return f;
end $$;

-- Must run in the SAME transaction as SQL lookup/attest/commit (no standalone
-- check followed by separate RPC). External Storage cannot share this lock:
-- enforce immutable create-only paths; re-check before attestation/commit,
-- retain any orphan, never purge in certification.
create function archivito_inc_cert_candidate.assert_fence(
  p_window uuid,p_archive uuid,p_actor uuid,p_key text,p_memory uuid,
  p_operation uuid,p_generation bigint,p_token uuid,p_digest text,p_renew boolean default false
) returns void
language plpgsql security invoker set search_path='' as $$
declare w archivito_inc_cert_candidate.windows%rowtype; f archivito_inc_cert_candidate.fences%rowtype; t timestamptz;
begin
  w:=archivito_inc_cert_candidate.guard_window(p_window,p_archive,p_actor,p_key,p_memory);
  select * into f from archivito_inc_cert_candidate.fences
    where window_id=p_window and operation_id=p_operation for update;
  t:=clock_timestamp();
  if not found or t>=w.expires_at or t>=f.lease_until or p_actor is distinct from f.actor
     or p_memory is distinct from f.memory_id or p_generation is distinct from f.generation
     or p_token is distinct from f.token or p_digest is distinct from f.wire_digest
  then raise exception using errcode='42501',message='certification fence denied';end if;
  if p_renew is true then
    update archivito_inc_cert_candidate.fences set lease_until=least(t+interval '30 seconds',w.expires_at)
    where window_id=p_window and operation_id=p_operation;
  end if;
end $$;
